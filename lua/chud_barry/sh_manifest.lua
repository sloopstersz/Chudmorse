function kit.Replacement(path)
    if not isstring(path) then return path end
    local normal = string.lower(string.gsub(path, "\\", "/"))
    local prefix = string.sub(normal, 1, 6) == "sound/" and "sound/" or ""
    local key = string.sub(normal, #prefix + 1)
    local flags = string.match(key, "^[*#@><^)}!?]+") or ""
    key = string.sub(key, #flags + 1)
    local target = kit.Tracks[key]
    if not target then return path end
    local replacement = "chudmorse/music_kits/barry/" .. target
    if not file.Exists("sound/" .. replacement, "GAME") then return path end
    return prefix .. flags .. replacement
end
